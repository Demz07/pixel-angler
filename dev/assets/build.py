import json, re
d  = json.load(open('assets/frames.json'))
df = json.load(open('assets/frames-fish.json'))
dw = json.load(open('assets/frames-wait.json'))
bg = json.load(open('assets/bg.json'))
ic = json.load(open('assets/fish-icons.json'))
wk = json.load(open('assets/frames-walk.json'))
ui = json.load(open('assets/ui.json'))
fr = json.load(open('assets/frames-fish.json'))
wr = json.load(open('assets/frames-wait.json'))
ct = json.load(open('assets/ctrl.json'))
html = open('template.html').read()
html = html.replace('__FRAMES_JSON__', json.dumps(d['frames']))
html = html.replace('__ANCHORS_JSON__', json.dumps(d['anchors']))
html = html.replace('__SPRW__', str(d['w'])).replace('__SPRH__', str(d['h']))
html = html.replace('__FISH_FRAMES_JSON__', json.dumps(df['frames']))
html = html.replace('__FISH_ANCHORS_JSON__', json.dumps(df['anchors']))
html = html.replace('__FISHW__', str(df['w'])).replace('__FISHH__', str(df['h']))
html = html.replace('__WAIT_FRAMES_JSON__', json.dumps(dw['frames']))
html = html.replace('__WAIT_ANCHORS_JSON__', json.dumps(dw['anchors']))
html = html.replace('__WAITW__', str(dw['w'])).replace('__WAITH__', str(dw['h'])).replace('__WAITCX__', str(dw['cx']))
html = html.replace('__FEET_JSON__', json.dumps(d['feet']))
html = html.replace('__FISHFEET_JSON__', json.dumps(df['feet']))
html = html.replace('__WAITFEET_JSON__', json.dumps(dw['feet']))
html = html.replace('__BG_JSON__', json.dumps(bg['uri']))
html = html.replace('__BGN_JSON__', json.dumps(bg['uriNight']))
html = html.replace('__SHORE_JSON__', json.dumps(bg['uriShore']))
html = html.replace('__SHOREN_JSON__', json.dumps(bg['uriShoreN']))
fa_keys = ['fishJ']
html = html.replace('__FAUNA_JSON__', json.dumps({k: ct[k] for k in fa_keys}))
html = html.replace('__ICONS_JSON__', json.dumps(ic))
html = html.replace('__WALK_JSON__', json.dumps(wk))
html = html.replace('__FISHR_JSON__', json.dumps({'framesR': fr['framesR'], 'anchorsR': fr['anchorsR'], 'feetR': fr['feetR'], 'cxR': fr['cxR'], 'w': fr['w'], 'h': fr['h']}))
html = html.replace('__WAITR_JSON__', json.dumps({'framesR': wr['framesR'], 'anchorsR': wr['anchorsR'], 'feetR': wr['feetR'], 'cxR': wr['cxR'], 'w': wr['w'], 'h': wr['h']}))
html = html.replace('__UIPANEL_JSON__', json.dumps(ui['panel']))
html = html.replace('__UIPLAQUE_JSON__', json.dumps(ui['plaque']))
html = html.replace('__UIPANEL_CSS__', 'url("' + ui['panel'] + '")')
html = html.replace('__UIPLAQUE_CSS__', 'url("' + ui['plaque'] + '")')
html = html.replace('__UIBANNER_CSS__', 'url("' + ui['banner'] + '")')
html = html.replace('__RIDGE_JSON__', json.dumps(bg['uriRidge']))
html = html.replace('__RIDGEN_JSON__', json.dumps(bg['uriRidgeN']))
html = html.replace('__ICARROW_CSS__', 'url("' + ct['arrow'] + '")')
html = html.replace('__ICHOOK_CSS__', 'url("' + ct['hook'] + '")')
html = html.replace('__ICBOBBER_CSS__', 'url("' + ct['bobber'] + '")')
html = html.replace('__FR_CSS__', 'url("' + ct['fr'] + '")')
html = html.replace('__FRP_CSS__', 'url("' + ct['frp'] + '")')
html = html.replace('__PLANK_CSS__', 'url("' + ct['plank'] + '")')
html = html.replace('__ROCK_CSS__', 'url("' + ct['rock'] + '")')
for key, ph in (('note','__ICNOTE_CSS__'), ('speak','__ICSPEAK_CSS__'), ('bag','__ICBAG_CSS__'),
                ('book','__ICBOOK_CSS__'), ('scroll','__ICSCROLL_CSS__'), ('x','__ICX_CSS__'), ('coin','__ICCOIN_CSS__')):
    html = html.replace(ph, 'url("' + ct[key] + '")')
html = html.replace('__LOGO_CSS__', 'url("' + ct['logo'] + '")')
html = html.replace('__SEP_CSS__', 'url("' + ct['sep'] + '")')
html = html.replace('__ICFISH_CSS__', 'url("' + ct['fishJ'] + '")')
html = html.replace('__JOYB_CSS__', 'url("' + ct['joyb'] + '")')
html = html.replace('__JOYK_CSS__', 'url("' + ct['joyk'] + '")')
html = html.replace('__GEARTAB_CSS__', 'url("' + ct['geartab'] + '")')
open('fishing-sim.html','w').write(html)
js = re.search(r'<script>(.*)</script>', html, re.S).group(1)
open('/tmp/check.js','w').write(js)
print('rebuilt', len(html)//1024, 'KB')
